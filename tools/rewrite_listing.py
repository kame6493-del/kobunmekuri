"""store/listing.md の説明文と Play の短い説明を書き直す(App Store 4.3(a) 対策)。
例文と出典を先頭に出し、ほかのアプリと同じ「苦手」の言葉と見出しの型(■)をやめる。何度流しても同じ結果。
python tools/rewrite_listing.py"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DESC = """六月の頃あやしき家に、夕顔の白く見えて、蚊遣火ふすぶるもあはれなり。(徒然草・第十九段)

この一文の「あはれなり」は、どんな意味でしょう。こぶんめくりは、古文単語を古典の本文の中で覚える単語帳です。大学受験・共通テストに出る601語のすべてに、著作権の切れた古典から引いた例文が1文ずつ付いています。

例文の出どころは、源氏物語211語、徒然草151語、枕草子65語、更級日記45語、方丈記42語、竹取物語ほか。どの例文にも作品名と巻・段を添えました。本文はウィキソース所収の翻刻から引いて字体を新字体に改め、現代語訳と解説はこのアプリのために書き下ろしています。意味は古語辞典の一般的な語義と照らして、書いた人とは別の観点でもう一度全語を見直しています。

古語は場面で意味が変わります。「例文で当てる」では、本文の一文の中で、その場の意味を選びます。ほかに、古語を見て意味を選ぶ4択、意味を見て古語を選ぶ4択、思い出してからめくる一問一答カードがあります。

間違えた語は一覧に残り、2回続けて正解すると消えます。覚えた語は1日後・3日後・1週間後・2週間後と間をあけて「今日の復習」に戻ってきます。試験日を入れると、残りの日数から1日に覚える語数を出します。

敬語セット(42語)では尊敬・謙譲・丁寧の見分けと普通の語への言い換えを、助動詞セット(28語)では意味と接続、例文の中での意味の見分けを練習できます。

無料で使えるのは、重要度の上位150語と、まちがえた語の練習・今日の復習・試験日からの逆算、例文問題5問のおためしです。完全版(買い切り・1回だけ)で、601語すべてと例文モード、敬語セット、助動詞セットが開きます。広告は無料でも完全版でも出しません。

アカウント登録はいりません。学習の記録はこの端末の中だけに保存し、外部へ送りません。
"""

SHORT = "古文単語601語を、源氏物語や徒然草の本文の一文で覚える。全語に例文と出典の巻・段つき。広告なし。"

p = os.path.join(ROOT, "store", "listing.md")
s = open(p, encoding="utf-8").read()
head, rest = s.split("## 説明文\n", 1)
body, tail = rest.split("\n## Google Play", 1)
s = head + "## 説明文\n\n" + DESC + "\n## Google Play" + tail
s = re.sub(r"(- 短い説明\(80字以内\): ).*", lambda m: m.group(1) + SHORT, s, count=1)
open(p, "w", encoding="utf-8", newline="").write(s)

p = os.path.join(ROOT, "store", "play", "listing.txt")
s = open(p, encoding="utf-8").read()
s = re.sub(r"(【短い説明\(80字以内\)】\n).*", lambda m: m.group(1) + SHORT, s, count=1)
open(p, "w", encoding="utf-8", newline="").write(s)
print("説明", len(DESC), "字 / 短い説明", len(SHORT), "字")
